let lang = 'ru';
try {
  const saved = localStorage.getItem('polivayka.lang');
  if (LANG_IDS.includes(saved)) lang = saved;
} catch (_) {}

function localeTag() { return LOCALE_TAG[lang] || 'ru-RU'; }

function t(key, vars) {
  const pack = UI[lang] || UI.ru;
  let s = (pack && pack[key] != null) ? pack[key]
    : (UI.en && UI.en[key] != null) ? UI.en[key]
    : (UI.ru && UI.ru[key] != null) ? UI.ru[key]
    : key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      s = s.split('{' + k + '}').join(vars[k] == null ? '' : String(vars[k]));
    });
  }
  return s;
}

function setLang(next) {
  if (!LANG_IDS.includes(next)) return;
  lang = next;
  try { localStorage.setItem('polivayka.lang', next); } catch (_) {}
  document.documentElement.lang = next;
}

function qtyWord(n, unit) {
  const rule = new Intl.PluralRules(localeTag()).select(Math.abs(Number(n) || 0));
  const direct = t(unit + '.' + rule);
  if (direct !== unit + '.' + rule) return direct;
  return t(unit + '.other');
}

function qty(n, unit) {
  return `${n} ${qtyWord(n, unit)}`;
}

function translateError(message) {
  if (!message) return t('serverErr');
  if (ERR_RU[message]) return t(ERR_RU[message]);
  const prefixes = [
    ['Не удалось загрузить модели: ', 'modelsFail'],
    ['Не удалось получить ответ: ', 'replyFail']
  ];
  for (const [prefix, key] of prefixes) {
    if (message.startsWith(prefix)) return t(key, { detail: message.slice(prefix.length) });
  }
  return message;
}

function langOptionsHtml(selected) {
  return LANGS.map((item) => `<option value="${item.id}" ${item.id === selected ? 'selected' : ''}>${item.name}</option>`).join('');
}
